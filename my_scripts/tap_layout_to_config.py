#!/usr/bin/env python3
"""Turn a TAP-2.5D placement into a perflp floorplan block or eval config.

TAP-2.5D (`sim_annealing.py`) reports its placements in `output.txt`
with `x`/`y` as chiplet **centres** in millimetres and a per-chiplet
`width`/`height` that may be rotated. perflp configs want the **lower-left
corner** in metres, in the chiplet order CPU, GPU, then the memory chiplets,
which is the order TAP uses as well.

    # from this repository's root:
    python my_scripts/tap_layout_to_config.py output/runs/run1/output.txt
    python my_scripts/tap_layout_to_config.py \
        --template ../config/eval/tap_four_mem_c45lat_d8.yaml \
        --out ../config/eval/tap_run1_four_mem_c45lat_d8.yaml \
        --report-path report/tap_runs/run1 output/runs/run1/output.txt

TAP's run-to-run variation comes from its unseeded RNG, so every run needs its
own output directory and its own converted config; this script is the bridge.
"""

import argparse
import re
from pathlib import Path

FIELDS = ("step_best", "cost_best", "temp_best", "length_best")


def parse_tap_output(path: Path) -> dict:
    """Read the `key = [..]` lines of a TAP-2.5D `output.txt`."""
    values = {}
    for line in path.read_text().splitlines():
        match = re.match(r"\s*(\w+)\s*=\s*(.*)$", line)
        if not match:
            continue
        key, raw = match.group(1), match.group(2).strip()
        if raw.startswith("["):
            values[key] = [float(item) for item in raw.strip("[]").split(",")]
        else:
            values[key] = raw
    missing = [key for key in ("x", "y", "width", "height") if key not in values]
    if missing:
        raise ValueError(f"{path}: missing {missing}")
    return values


def lower_left(values: dict, centres: bool) -> dict:
    """Convert centres plus sizes into the lower-left corners perflp stores."""
    x, y = values["x"], values["y"]
    width, height = values["width"], values["height"]
    if len({len(x), len(y), len(width), len(height)}) != 1:
        raise ValueError("x/y/width/height must have the same length")
    if centres:
        x = [cx - w / 2.0 for cx, w in zip(x, width)]
        y = [cy - h / 2.0 for cy, h in zip(y, height)]
    return {
        "x": [value / 1000.0 for value in x],
        "y": [value / 1000.0 for value in y],
        "width": [value / 1000.0 for value in width],
        "height": [value / 1000.0 for value in height],
    }


def format_block(geometry: dict, indent: str = "") -> str:
    """The `floorplan:` block as it appears in a perflp config."""
    def series(name):
        return "[" + ", ".join(repr(value) for value in geometry[name]) + "]"

    lines = [
        f"{indent}floorplan:",
        f"{indent}  source: given",
        f"{indent}  x: {series('x')}",
        f"{indent}  y: {series('y')}",
        f"{indent}  width: {series('width')}",
        f"{indent}  height: {series('height')}",
    ]
    return "\n".join(lines) + "\n"


def write_config(template: Path, geometry: dict, out: Path, report_path: str) -> None:
    """Copy an eval config and swap its floorplan block and report path."""
    text = template.read_text()
    block = re.compile(r"^floorplan:\n(?:[ \t]+.*\n)+", re.M)
    if not block.search(text):
        raise ValueError(f"{template} has no floorplan block to replace")
    text = block.sub(format_block(geometry), text, count=1)
    text = re.sub(r"^report_path: .*$", f"report_path: {report_path}", text, count=1, flags=re.M)
    text = (
        f"# Generated by scripts/tap_layout_to_config.py from a TAP-2.5D run;\n"
        f"# the placement is TAP's own output, not a hand-placed baseline.\n"
    ) + text
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("output_txt", type=Path, help="TAP-2.5D output.txt")
    parser.add_argument("--from-tap-centres", action="store_true", default=True,
                        help="TAP reports centres (default; keep for clarity)")
    parser.add_argument("--lower-left-input", dest="from_tap_centres", action="store_false",
                        help="the file already holds lower-left corners")
    parser.add_argument("--template", type=Path, default=None,
                        help="Eval config to copy when writing a config")
    parser.add_argument("--out", type=Path, default=None, help="Config to write")
    parser.add_argument("--report-path", default=None, help="report_path for the new config")
    args = parser.parse_args()

    values = parse_tap_output(args.output_txt)
    geometry = lower_left(values, args.from_tap_centres)
    summary = " ".join(f"{key}={values[key]}" for key in FIELDS if key in values)
    print(f"{args.output_txt}: {summary}")
    print(format_block(geometry), end="")
    if args.out is not None:
        if args.template is None:
            raise SystemExit("--out needs --template")
        report_path = args.report_path or f"report/tap_runs/{args.out.stem}"
        write_config(args.template, geometry, args.out, report_path)
        print(f"wrote {args.out} (report_path: {report_path})")


if __name__ == "__main__":
    main()
